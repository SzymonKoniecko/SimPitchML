from pathlib import Path
from typing import Dict, List, Optional, Protocol, Union

class JsonFileRepositoryPort(Protocol):
    def get_full_path(self, filename: str) -> Path: ...
    def load(self, filename: str) -> Optional[Union[Dict, list]]: ...
    def save(self, *, filename: str, data: dict) -> None: ...
    def delete(self, filename: str) -> bool: ...
    def delete_by_directory(self, patterns: list) -> int: ...
    def list_all_files(self) -> List[str]: ...